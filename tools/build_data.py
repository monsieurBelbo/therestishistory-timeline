#!/usr/bin/env python3
"""Merge data/feed.json (RSS dump) + data/classification.jsonl (period/region per episode) -> data/episodes.js"""
import json, re, os, collections, email.utils
D = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'data')
feed = json.load(open(os.path.join(D, 'feed.json')))
cls = {}
for line in open(os.path.join(D, 'classification.jsonl')):
    line = line.strip()
    if line:
        o = json.loads(line); cls[o['i']] = o
LANES = {'global','british-isles','w-europe','c-n-europe','s-europe','e-europe','n-africa','sub-africa','mideast','s-asia','c-asia','e-asia','se-asia-oceania','n-america','mesoamerica','s-america'}
def clean_desc(d):
    d = re.split(r'(_{3,}|Learn more about your ad choices|\*The Rest Is History|Twitter:|Producer:|Email: )', d)[0]
    return d.strip()
def series_from_title(t):
    m = re.match(r'^(.*?):', t)
    return m.group(1).strip() if m else None
out = []; bad = []
for i, e in enumerate(feed):
    c = cls.get(i)
    if not c: bad.append((i, 'missing')); continue
    if c['lane'] not in LANES: bad.append((i, 'lane ' + c['lane'])); c['lane'] = 'global'
    s, en = int(c['s']), int(c['e'])
    if en < s: s, en = en, s
    title = e['title']
    m = re.match(r'^(\d+)[.:]\s*(.*)$', title)
    num = int(m.group(1)) if m else (int(e['ep']) if e.get('ep', '').isdigit() and e['type'] == 'full' else None)
    short = m.group(2) if m else title
    try: date = email.utils.parsedate_to_datetime(e['date']).strftime('%Y-%m-%d')
    except Exception: date = ''
    out.append(dict(i=i, n=num, t=short, date=date, dur=int(e['dur'] or 0), a=e['audio'], s=s, e=en, l=c['lane'],
                    sr=c.get('series') or None, tp=c.get('topic') or '', th=bool(c.get('thematic')) or e['type'] == 'trailer',
                    c=c.get('conf', 'm'), d=clean_desc(e['desc'])))
# normalise series names: parts that share a title prefix share a series
by_prefix = collections.defaultdict(list)
for o in out:
    p = series_from_title(o['t'])
    if p: by_prefix[p].append(o)
for p, lst in by_prefix.items():
    if len(lst) > 1:
        names = collections.Counter(o['sr'] for o in lst if o['sr'])
        name = names.most_common(1)[0][0] if names else p
        for o in lst: o['sr'] = name
cnt = collections.Counter(o['sr'] for o in out if o['sr'])
for o in out:
    if o['sr'] and cnt[o['sr']] < 2: o['sr'] = None
with open(os.path.join(D, 'episodes.js'), 'w') as f:
    f.write('// generated by tools/build_data.py — do not edit; edit classification.jsonl instead\nwindow.EPISODES = ')
    json.dump(out, f, ensure_ascii=False, separators=(',', ':'))
    f.write(';\n')
print(len(out), 'episodes;', sum(o['th'] for o in out), 'thematic;', 'problems:', bad)
print(collections.Counter(o['l'] for o in out if not o['th']).most_common())
print('pre-3100:', [(o['t'][:30], o['s']) for o in out if o['s'] < -3100 and not o['th']])
print('span>400:', [(o['t'][:34], o['s'], o['e']) for o in out if o['e'] - o['s'] > 400 and not o['th']])
print('future/odd:', [(o['t'][:30], o['s'], o['e']) for o in out if o['e'] > 2026])
print('series:', len(set(o['sr'] for o in out if o['sr'])))
